#!/usr/bin/env node
/**
 * Generates TypeScript types from the Pydantic-exported JSON Schema in
 * protocol/schema/ (see beam_protocol/export_schema.py). Pydantic is the single
 * source of truth for the wire protocol (docs/architecture.md §2); this script is the
 * other half of that pipeline, and CI fails if its output would differ from what's
 * committed (see the `codegen:check` script in package.json).
 *
 * Usage: node scripts/codegen-protocol.mjs
 */
import { compile } from "json-schema-to-typescript";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SCHEMA_DIR = path.resolve(__dirname, "../../protocol/schema");
const OUT_DIR = path.resolve(__dirname, "../src/protocol/generated");

const BANNER = `/**
 * AUTO-GENERATED by scripts/codegen-protocol.mjs from protocol/schema/*.schema.json.
 * Do not edit by hand -- change the Pydantic models in protocol/src/beam_protocol/
 * and re-run \`npm run codegen\` instead. See docs/architecture.md §2.
 */
`;

async function main() {
  const files = (await readdir(SCHEMA_DIR)).filter((f) => f.endsWith(".schema.json"));
  if (files.length === 0) {
    throw new Error(`no *.schema.json files found in ${SCHEMA_DIR}`);
  }

  await mkdir(OUT_DIR, { recursive: true });

  // Deliberately no barrel index.ts re-exporting `*` from every module: each schema's
  // internal helper types (e.g. per-field enum aliases) are named independently by
  // json-schema-to-typescript, so two modules can both produce a `Type1` and collide
  // under a shared re-export. Each generated module is self-contained instead --
  // import the specific message type you need directly from its file, e.g.
  // `import type { ClientMessage } from "./generated/client-message"`.
  const moduleNames = [];
  for (const file of files) {
    const schemaText = await readFile(path.join(SCHEMA_DIR, file), "utf-8");
    const schema = JSON.parse(schemaText);
    const ts = await compile(schema, schema.title ?? file, {
      bannerComment: "",
      additionalProperties: false,
      style: { singleQuote: false },
    });

    const moduleName = file.replace(/\.schema\.json$/, "");
    moduleNames.push(moduleName);
    await writeFile(path.join(OUT_DIR, `${moduleName}.ts`), BANNER + "\n" + ts);
  }

  console.log(`Generated ${moduleNames.length} type file(s) into ${OUT_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
